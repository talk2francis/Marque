import fs from 'node:fs'
import path from 'node:path'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const target = 'packages/conformance/src/code-anchor.ts'
const files = []
function scan(dir) {
  for (const entry of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
    const name = `${dir}/${entry.name}`
    if (entry.isDirectory()) scan(name)
    else if (entry.isFile() && name.endsWith('.ts') && !name.endsWith('.test.ts') && name !== target) files.push(name)
  }
}
for (const pkg of ['conformance', 'positions', 'chain', 'probe', 'db']) scan(`packages/${pkg}/src`)
files.push('pnpm-lock.yaml')
const sha = bytes => `0x${createHash('sha256').update(bytes).digest('hex')}`
const manifest = files.sort().map(name => ({ path: name, sha256: sha(fs.readFileSync(path.join(root, name))) }))
const anchor = { version: 1, algorithm: 'SHA-256', sha256: sha(JSON.stringify(manifest)), scope: 'local MCS implementation and imported workspace source; lockfile pins external dependencies; not deployed-bytecode or issuer attestation', files: manifest }
const text = `// Generated by scripts/generate-mcs-code-anchor.mjs; do not edit.\nexport const MCS_CODE_ANCHOR = ${JSON.stringify(anchor, null, 2)} as const\n`
if (process.argv.includes('--check')) {
  if (!fs.existsSync(path.join(root, target)) || fs.readFileSync(path.join(root, target), 'utf8') !== text) throw Error('MCS source anchor differs; regenerate and review')
} else fs.writeFileSync(path.join(root, target), text)
console.log(JSON.stringify({ codeHash: anchor.sha256, sourceFiles: manifest.length, check: process.argv.includes('--check') }))
