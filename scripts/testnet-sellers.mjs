#!/usr/bin/env node
/**
 * The practice lane's reference sellers (BSC testnet, 97).
 *
 *   node scripts/testnet-sellers.mjs [--check] [--keystore-root=/root/marque]
 *
 * For each reference agent with a testnet identity, writes agents/<name>/.testnet/studio.toml:
 * the agent's own mainnet config with exactly four changes, so the same code, engine and
 * wallet sell on testnet under their own process (ecosystem.config.cjs, marque-<name>-testnet):
 *   network      bsc-mainnet -> bsc-testnet
 *   currency     mainnet U   -> testnet U (the testnet escrow's paymentToken)
 *   keystore_dir relative    -> the agent's own keystore, absolute (same wallet as mainnet)
 *   x402 seller  enabled     -> disabled (the practice lane sells through ERC-8183 escrow only)
 * Prices and limits are unchanged. The directory is git-ignored (it holds the seller's
 * testnet audit log and deliverables). --check verifies without writing.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { join, resolve, dirname } from 'node:path'

const ROOT = resolve(dirname(new URL(import.meta.url).pathname), '..')
const TESTNET_U = '0xc70B8741B8B07A6d61E54fd4B20f22Fa648E5565'
const MAINNET_U = /0xcE24439F2D9C6a2289F741120FE202248B666666/i
const fp = JSON.parse(readFileSync(join(ROOT, 'config/first-party.json'), 'utf8'))
const check = process.argv.includes('--check')
// Where the agents' keystores live (the production checkout); defaults to this checkout.
const KEYS = resolve(process.argv.find((x) => x.startsWith('--keystore-root='))?.split('=')[1] ?? ROOT)
let failures = 0

for (const a of fp.agents) {
  if (!a.testnet) continue
  const dir = join(ROOT, 'agents', a.slug)
  const src = readFileSync(join(dir, 'studio.toml'), 'utf8')
  let out = src
    .replace(/^default\s*=\s*"bsc-mainnet"/m, 'default = "bsc-testnet"')
    .replace(/^(currency\s*=\s*)"0x[0-9a-fA-F]{40}"(.*)$/m, `$1"${TESTNET_U}"   # U on BSC testnet: the testnet escrow's paymentToken() (practice lane)`)
    .replace(/^keystore_dir\s*=.*$/m, `keystore_dir = "${join(KEYS, 'agents', a.slug, '.studio/wallets')}"`)
    .replace(/(\[payments\.b402_seller\][^[]*?)enabled\s*=\s*true/s, '$1enabled = false')
  const ok = /default = "bsc-testnet"/.test(out) && out.includes(TESTNET_U) && !MAINNET_U.test(out.split('[payments.erc8183]')[1]?.split('\n[')[0] ?? '')
    && out.includes(join(KEYS, 'agents', a.slug, '.studio/wallets'))
  if (!ok) { console.error(`${a.slug}: could not derive a testnet config`); failures++; continue }
  out = `# GENERATED by scripts/testnet-sellers.mjs from ../studio.toml. Do not edit by hand.\n${out}`
  const target = join(dir, '.testnet', 'studio.toml')
  if (check) {
    const same = existsSync(target) && readFileSync(target, 'utf8') === out
    console.log(`${a.slug}: ${same ? 'up to date' : 'needs regeneration'}`)
    if (!same) failures++
  } else {
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, out)
    console.log(`${a.slug}: wrote ${target} (testnet #${a.testnet.tokenId})`)
  }
}
process.exit(failures ? 1 : 0)
