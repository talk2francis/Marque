#!/usr/bin/env node
// Writes apps/web/lib/forge-starter-sources.ts from examples/starters/<category>/{src/task.ts,test/live-task.test.ts},
// so the Forge zip ships exactly the parser and live-task test that the starters are tested with (23 Nov 2026: the
// zip's own copy could not read Marque's live tasks). Run after editing a starter; a test fails if they drift.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const CATS = ['health_factor', 'yield', 'grid', 'rebalancing']
const out = {}
for (const c of CATS) {
  const task = readFileSync(path.join(ROOT, 'examples/starters', c, 'src/task.ts'), 'utf8')
  const a = task.indexOf('export function parseTask')
  const b = task.indexOf('\n}\n', a)
  const body = task.slice(task.indexOf('\n', a) + 1, b + 1).replace(/\n$/, '')
  const ti = task.indexOf('export interface Task')
  const taskType = task.slice(ti, task.indexOf('\n}\n', ti) + 2)
  out[c] = { parse: body.split('\n'), taskType: taskType.split('\n'), liveTest: readFileSync(path.join(ROOT, 'examples/starters', c, 'test/live-task.test.ts'), 'utf8') }
}
writeFileSync(path.join(ROOT, 'apps/web/lib/forge-starter-sources.ts'),
  `// GENERATED by scripts/gen-forge-starter-sources.mjs from examples/starters. Do not edit by hand.\n` +
  `export const STARTER_SOURCES: Record<'health_factor' | 'yield' | 'grid' | 'rebalancing', { parse: string[]; taskType: string[]; liveTest: string }> = ${JSON.stringify(out, null, 2)}\n`)
console.log('wrote apps/web/lib/forge-starter-sources.ts')
