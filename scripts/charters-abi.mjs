#!/usr/bin/env node
// Writes packages/charters/src/abi.ts from Foundry's compiled output, so the ABIs the app uses are exactly the
// ABIs of the reviewed contracts. Run after `forge build` in contracts/:  node scripts/charters-abi.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'

const out = new URL('../contracts/out/', import.meta.url)
const read = (file, name) => JSON.parse(readFileSync(new URL(`${file}/${name}.json`, out), 'utf8'))
const guard = read('LoanGuard.sol', 'LoanGuard')
const factory = read('CharterFactory.sol', 'CharterFactory')
// The LoanGuard creation code is what predict() hashes; recording its digest lets anyone match a deployed guard.
const creationHash = '0x' + createHash('sha256').update(Buffer.from(guard.bytecode.object.slice(2), 'hex')).digest('hex')

const body = `// Generated by scripts/charters-abi.mjs from contracts/out. Do not edit by hand.
// LoanGuard creation code sha256: ${creationHash}

export const loanGuardAbi = ${JSON.stringify(guard.abi, null, 2)} as const

export const charterFactoryAbi = ${JSON.stringify(factory.abi, null, 2)} as const
`
writeFileSync(new URL('../packages/charters/src/abi.ts', import.meta.url), body)
console.log(`wrote packages/charters/src/abi.ts (${guard.abi.length} guard items, ${factory.abi.length} factory items)`)
